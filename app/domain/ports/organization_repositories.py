from typing import Protocol, Sequence

from app.domain.entities.organization_models import (
    Department,
    Document,
    Project,
    User,
    UserProject,
)


class UserRepository(Protocol):
    def get_by_uid(self, uid: str) -> User | None: ...
    def get_by_email(self, email: str) -> User | None: ...
    def list(self) -> Sequence[User]: ...
    def save(self, user: User) -> User: ...
    def delete(self, uid: str) -> None: ...


class DepartmentRepository(Protocol):
    def get(self, department_id: str) -> Department | None: ...
    def list(self) -> Sequence[Department]: ...
    def save(self, department: Department) -> Department: ...


class ProjectRepository(Protocol):
    def get(self, project_id: str) -> Project | None: ...
    def list_active(self) -> Sequence[Project]: ...
    def save(self, project: Project) -> Project: ...


class DocumentRepository(Protocol):
    def get(self, document_id: str) -> Document | None: ...
    def list(self) -> Sequence[Document]: ...
    def save(self, document: Document) -> Document: ...
    def delete(self, document_id: str) -> None: ...


class MembershipRepository(Protocol):
    def get(self, uid: str, project_id: str) -> UserProject | None: ...
    def list_for_user(self, uid: str) -> Sequence[UserProject]: ...
    def list_for_project(self, project_id: str) -> Sequence[UserProject]: ...
    def save(self, membership: UserProject) -> UserProject: ...
    def revoke(self, uid: str, project_id: str) -> None: ...
