from app.domain.entities.organization_models import Department, Project, User
from app.domain.services.organization_errors import ForbiddenError
from app.infrastructure.persistence.sqlalchemy.session import create_engine_and_session_factory, initialize_database
from app.infrastructure.persistence.sqlalchemy.unit_of_work import SqlAlchemyUnitOfWork
from app.use_cases.organization.project_management import ProjectManagementService
from app.use_cases.organization.membership_management import MembershipManagementService


def _seed():
    engine, session_factory = create_engine_and_session_factory("sqlite:///:memory:")
    initialize_database(engine)
    with SqlAlchemyUnitOfWork(session_factory) as uow:
        uow.departments.save(Department("d1", "Engineering"))
        uow.departments.save(Department("d2", "QA"))
        uow.users.save(User("a1", "Admin", "a@example.com", "Admin", "d1"))
        uow.users.save(User("m1", "Manager", "m@example.com", "Developer", "d1"))
        uow.users.save(User("u1", "User", "u@example.com", "Developer", "d1"))
        uow.commit()
    return engine, session_factory


def test_created_project_persists_internal_id_in_database():
    _, session_factory = _seed()
    service = ProjectManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    project = service.create_project("a1", "e2e-1", "Project A", "d1", description="E2E", manager_uid="m1")
    assert project.internal_id is not None
    assert project.project_id == "e2e-1"

    with SqlAlchemyUnitOfWork(session_factory) as uow:
        stored = uow.projects.get("e2e-1")
        assert stored.internal_id == project.internal_id
        assert stored.description == "E2E"
        assert stored.manager_uid == "m1"
        assert stored.created_by_uid == "a1"
        by_internal = uow.projects.get_by_internal_id(project.internal_id)
        assert by_internal.project_id == "e2e-1"


def test_autogenerated_project_id_is_sequential_in_database():
    _, session_factory = _seed()
    service = ProjectManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    first = service.create_project("a1", project_name="Project A", department_id="d1")
    second = service.create_project("a1", project_name="Project B", department_id="d1")
    assert first.project_id == "PROJ-001"
    assert second.project_id == "PROJ-002"
    assert first.internal_id != second.internal_id


def test_project_manager_cannot_manage_unrelated_project_in_database():
    _, session_factory = _seed()
    projects = ProjectManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    service = MembershipManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    projects.create_project("a1", "p1", "Project A", "d1", manager_uid="m1")
    projects.create_project("a1", "p2", "Project B", "d1")

    service.assign("m1", "u1", "p1")
    try:
        service.assign("m1", "u1", "p2")
    except ForbiddenError:
        pass
    else:
        raise AssertionError("project manager managed an unrelated project")

    with SqlAlchemyUnitOfWork(session_factory) as uow:
        assert len(uow.memberships.list_for_project("p1")) == 1
        assert len(uow.memberships.list_for_project("p2")) == 0


def test_user_can_leave_project_in_database():
    _, session_factory = _seed()
    projects = ProjectManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    service = MembershipManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))
    projects.create_project("a1", "p1", "Project A", "d1")
    service.assign("a1", "u1", "p1")
    service.leave("u1", "p1")

    with SqlAlchemyUnitOfWork(session_factory) as uow:
        membership = uow.memberships.get("u1", "p1")
        assert membership.status == "left"
        assert membership.left_at is not None