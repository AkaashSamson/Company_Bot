from app.domain.entities.organization_models import Department, Project, User
from app.domain.ports.authorization_service import AuthenticatedPrincipal
from app.infrastructure.persistence.sqlalchemy.session import create_engine_and_session_factory, initialize_database
from app.infrastructure.persistence.sqlalchemy.unit_of_work import SqlAlchemyUnitOfWork
from app.use_cases.organization.document_management import DocumentManagementService


def _seed():
    engine, session_factory = create_engine_and_session_factory("sqlite:///:memory:")
    initialize_database(engine)
    with SqlAlchemyUnitOfWork(session_factory) as uow:
        uow.departments.save(Department("d1", "Engineering"))
        uow.users.save(User("a1", "Admin", "a@example.com", "Admin", "d1"))
        uow.projects.save(Project("p1", "Project One", "d1"))
        uow.commit()
    return engine, session_factory


def test_document_metadata_roundtrips_through_database():
    _, session_factory = _seed()
    service = DocumentManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))

    document = service.register_document(
        AuthenticatedPrincipal("a1"),
        document_id="doc-meta-1",
        document_name="Policy.txt",
        project_id="p1",
        original_filename="policy v2.txt",
        file_type="txt",
        description="Updated policy",
        version="2.0",
    )
    assert document.internal_id is not None

    with SqlAlchemyUnitOfWork(session_factory) as uow:
        stored = uow.documents.get("doc-meta-1")
        assert stored.internal_id is not None
        assert stored.project_id == "p1"
        assert stored.original_filename == "policy v2.txt"
        assert stored.file_type == "txt"
        assert stored.description == "Updated policy"
        assert stored.version == "2.0"
        assert stored.uploaded_by == "a1"
        assert stored.uploaded_at is None

        by_id = uow.documents.get_by_internal_id(stored.internal_id)
        assert by_id.document_id == "doc-meta-1"


def test_autogenerated_document_ids_are_sequential_in_database():
    _, session_factory = _seed()
    service = DocumentManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))

    first = service.register_document(AuthenticatedPrincipal("a1"), document_name="A.txt", project_id="p1")
    second = service.register_document(AuthenticatedPrincipal("a1"), document_name="B.txt", project_id="p1")

    assert first.document_id == "DOC-001"
    assert second.document_id == "DOC-002"
    assert first.internal_id != second.internal_id


def test_default_version_persists_in_database():
    _, session_factory = _seed()
    service = DocumentManagementService(lambda: SqlAlchemyUnitOfWork(session_factory))

