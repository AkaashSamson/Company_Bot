def test_business_ids_are_not_the_internal_database_primary_keys():
    uow = InMemoryUnitOfWork(users=[User("admin", "Admin", "admin@example.com", "Admin", "d1")])
    generator = build_business_id_generator(
        user_prefix="MSS", department_prefix="DEPT", project_prefix="PROJ", document_prefix="DOC"
    )
    with uow:
        project = Project("p1", "Legacy", "d1")
        saved = uow.projects.save(project)
        business_id = generator.next(uow, "project")
        assert business_id == "PROJ-001"
        # The generated business ID never collides with or replaces the internal integer id.
        assert isinstance(saved.internal_id, int)
        assert str(saved.internal_id) != business_id
        assert business_id != saved.project_id


def test_employee_ids_are_never_reused_after_user_deletion():
    admin = User("admin", "Admin", "admin@example.com", "Admin", "d1")
    uow = InMemoryUnitOfWork([admin], [Department("d1", "Engineering")])
    service = UserManagementService(lambda: uow)

    first = service.create_user("admin", "u1", "A", "a@example.com", "Developer", "d1")
    second = service.create_user("admin", "u2", "B", "b@example.com", "Developer", "d1")
    third = service.create_user("admin", "u3", "C", "c@example.com", "Developer", "d1")
    assert [first.employee_id, second.employee_id, third.employee_id] == ["MSS-001", "MSS-002", "MSS-003"]

    uow.users.delete("u3")

    fourth = service.create_user("admin", "u4", "D", "d@example.com", "Developer", "d1")
    assert fourth.employee_id == "MSS-004"


def test_parallel_generation_with_shared_in_memory_counter_has_no_duplicates():
    uow = InMemoryUnitOfWork()
    generator = build_business_id_generator(
        user_prefix="MSS", department_prefix="DEPT", project_prefix="PROJ", document_prefix="DOC"
    )
    threads = 8
    each = 50

    def allocate_batch(_):
        return [generator.next(uow, "user") for _ in range(each)]

    with ThreadPoolExecutor(max_workers=threads) as pool:
        batches = list(pool.map(allocate_batch, range(threads)))

    values = [value for batch in batches for value in batch]
    assert len(values) == threads * each
    assert len(set(values)) == len(values)
    numbers = sorted(int(value.split("-")[1]) for value in values)
    assert numbers == list(range(1, threads * each + 1))


