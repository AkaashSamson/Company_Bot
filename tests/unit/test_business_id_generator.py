def test_highest_existing_suffix_ignores_non_matching_ids():
    ids = ["MSS-001", "MSS-005", "MSS-x", "other", "NEX-002", "", None]
    assert highest_existing_suffix(ids, "MSS") == 5
    assert highest_existing_suffix([], "MSS") == 0


def test_generated_format_is_prefix_hyphen_padded_suffix():
    uow = InMemoryUnitOfWork()
