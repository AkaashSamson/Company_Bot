def test_description_longer_than_500_characters_is_rejected():
    unit_of_work = InMemoryUnitOfWork(users=[User("admin", "Admin", "admin@example.com", "Admin", "d1")])
    service = DocumentManagementService(lambda: unit_of_work)

    with pytest.raises(ValueError):
        service.register_document(AuthenticatedPrincipal("admin"), document_name="F.txt", description="x" * 501)