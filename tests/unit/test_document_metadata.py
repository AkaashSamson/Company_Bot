def test_registration_captures_upload_metadata():
    unit_of_work = InMemoryUnitOfWork(users=[User("admin", "Admin", "admin@example.com", "Admin", "d1")])
    service = DocumentManagementService(lambda: unit_of_work)

    document = service.register_document(
        AuthenticatedPrincipal("admin"),
        document_id="meta-1",
        document_name="Policy.txt",
        original_filename="policy v3.txt",
        file_type="txt",
        description="Company policy v3",
        content="aGVsbG8=",
    )

    assert document.uploaded_by == "admin"
    assert document.uploaded_at is not None
    assert document.original_filename == "policy v3.txt"
    assert document.file_type == "txt"
    assert document.description == "Company policy v3"
    assert document.version == "1.0"
    assert document.status == "active"
    assert document.internal_id is not None


