import pytest

from app.domain.entities.organization_models import Document, User
from app.domain.ports.authorization_service import AuthenticatedPrincipal
from app.use_cases.organization.document_management import DocumentManagementService
from tests.fixtures.organization_repositories import InMemoryUnitOfWork


def test_autogenerated_document_ids_are_sequential():
    unit_of_work = InMemoryUnitOfWork(users=[User("admin", "Admin", "admin@example.com", "Admin", "d1")])
    service = DocumentManagementService(lambda: unit_of_work)

    first = service.register_document(AuthenticatedPrincipal("admin"), document_name="A.txt")
    second = service.register_document(AuthenticatedPrincipal("admin"), document_name="B.txt")

    assert first.document_id == "DOC-001"
    assert second.document_id == "DOC-002"


def test_autogenerated_id_scans_for_highest_suffix():
    unit_of_work = InMemoryUnitOfWork(
        users=[User("admin", "Admin", "admin@example.com", "Admin", "d1")],
        documents=[Document("DOC-007", "Existing")],
    )
    service = DocumentManagementService(lambda: unit_of_work)

    document = service.register_document(AuthenticatedPrincipal("admin"), document_name="C.txt")

    assert document.document_id == "DOC-008"


